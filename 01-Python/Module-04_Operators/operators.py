"""Operators"""

#1. ARITHMATIC OPERATORS(+,-,*,/,//,%,**)

a = 5
b = 20 

print(a + b)
print(b - a)
print(a * b)
print(b/a)
print(b//a)
print(5**3)
print(32%5)

print(12+4/2)


#2. ASSIGNMENT OPERATORS(+= ,-= , *= , /= ,//= , %= , **= )
c = 40

c += 30
print(c)

#3. COMPARISON OPERATORS (==, != , > , < , >= , <= )

d = 12
e = 12
print(d == e)
print(d != e)

f = 8
print(f>e)
print(23>=23)


#4. LOGICAL OPERATORS(AND, OR ,NOT)
print(123 > 20 and 123 > 100 and 34 == 34)

print(12 != 12 or 23 < 55 )

print(not 24 == 24)
